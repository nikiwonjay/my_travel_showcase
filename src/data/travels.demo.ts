function photos(prefix: string, count: number, offset = 0): TravelPhoto[] {
  return Array.from({ length: count }, (_, index) => ({
    src: sampleImages[(index + offset) % sampleImages.length],
    caption: `${prefix} · 示例照片 ${index + 1}`,
    date: `202${4 + Math.floor(index / 12)}-${String((index % 9) + 1).padStart(2, '0')}`,
    comment: index % 4 === 0 ? '公开展示用的虚构文字，不对应任何真实人物或行程。' : undefined,
  }));
}

